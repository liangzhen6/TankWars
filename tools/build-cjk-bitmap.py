#!/usr/bin/env python3
"""Generate the Switch CJK bitmap font module.

Scans every quoted string in game.js and switch/src/main.js, rasterizes each
non-ASCII character into a 14x14 1-bit cell using the source font (Noto Sans
SC, SIL OFL), and writes switch/src/cjk-glyphs.js.

The Switch runtime cannot be trusted to load custom font faces (the NX.js
font path stalled the app on device), so the localized UI is drawn with these
bitmaps via fillRect only.

Usage:
  python3 tools/build-cjk-bitmap.py /path/to/NotoSansSC_400Regular.ttf
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [ROOT / "game.js", ROOT / "switch/src/main.js"]
OUTPUT = ROOT / "switch/src/cjk-glyphs.js"

CELL = 14
ADVANCE = 15
THRESHOLD = 110
STRING_RE = re.compile(r"""(?s)(['"`])(?:\\.|(?!\1).)*\1""")


def collect_chars() -> list[str]:
    chars = set()
    for path in SOURCES:
        source = path.read_text(encoding="utf-8")
        for match in STRING_RE.finditer(source):
            for ch in match.group(0):
                if ord(ch) > 0x7E:
                    chars.add(ch)
    return sorted(chars)


def rasterize(font: ImageFont.FreeTypeFont, ch: str) -> list[str]:
    img = Image.new("L", (CELL, CELL), 0)
    draw = ImageDraw.Draw(img)
    bbox = draw.textbbox((0, 0), ch, font=font)
    width = bbox[2] - bbox[0]
    height = bbox[3] - bbox[1]
    x = (CELL - width) // 2 - bbox[0]
    y = CELL - height - bbox[1]
    draw.text((x, y), ch, font=font, fill=255)
    rows = []
    for row in range(CELL):
        bits = "".join(
            "1" if img.getpixel((col, row)) > THRESHOLD else "0"
            for col in range(CELL)
        )
        rows.append(bits)
    return rows


def main() -> None:
    if len(sys.argv) != 2:
        print(__doc__)
        raise SystemExit(2)
    source_font = Path(sys.argv[1])
    font = ImageFont.truetype(str(source_font), CELL)
    chars = collect_chars()
    glyphs = {ch: rasterize(font, ch) for ch in chars}

    missing = [ch for ch, rows in glyphs.items() if "1" not in "".join(rows)]
    if missing:
        print("blank glyphs:", "".join(missing))
        raise SystemExit(1)

    lines = [
        "// Generated by tools/build-cjk-bitmap.py from Noto Sans SC (SIL OFL).",
        "// Do not edit by hand; rerun the script after changing UI copy.",
        f"export const CJK_CELL = {CELL};",
        f"export const CJK_ADVANCE = {ADVANCE};",
        "export const CJK_GLYPHS = Object.freeze({",
    ]
    for ch in chars:
        rows = ", ".join(f'"{row}"' for row in glyphs[ch])
        lines.append(f'  "{ch}": [{rows}],')
    lines.append("});")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUTPUT}  {OUTPUT.stat().st_size / 1024:.1f} KiB  {len(chars)} glyphs")


if __name__ == "__main__":
    main()
